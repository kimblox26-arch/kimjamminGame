let X = null;
function mats() {
  const m = gunMats();
  if (X) return m;
  const rep = (t, n) => { const c = t.clone(); c.repeat.set(n, n); c.needsUpdate = true; return c; };
  const st = T.stipple, an = T.anodized;
  const poly = (color, r = 1) => new THREE.MeshStandardMaterial({ color, roughnessMap: rep(st.roughnessMap, 14), normalMap: rep(st.normalMap, 14), normalScale: new THREE.Vector2(0.6, 0.6), roughness: r, metalness: 0, envMapIntensity: 0.9 });
  const metal = (color, r = 1, me = 0.6) => new THREE.MeshPhysicalMaterial({ color, map: rep(an.map, 10), roughnessMap: rep(an.roughnessMap, 10), normalMap: rep(an.normalMap, 10), normalScale: new THREE.Vector2(0.35, 0.35), roughness: r, metalness: me, clearcoat: 0.2, clearcoatRoughness: 0.4 });
  Object.assign(m, {
    fde: poly(0x9a8565), fdeMetal: metal(0x8e7b5d, 1.05, 0.45), plum: poly(0x5c2e24), odg: poly(0x4b5237),
    chrome: new THREE.MeshPhysicalMaterial({ color: 0xc8c8c8, roughness: 0.18, metalness: 1, clearcoat: 0.5 }),
    smoke: new THREE.MeshPhysicalMaterial({ color: 0x2a2620, roughness: 0.25, metalness: 0, transmission: 0, transparent: true, opacity: 0.82 }),
    woodDark: new THREE.MeshPhysicalMaterial({ color: 0x6a4028, map: rep(T.gunwood.map, 3), roughnessMap: rep(T.gunwood.roughnessMap, 3), normalMap: rep(T.gunwood.normalMap, 3), roughness: 1.4, clearcoat: 0.25 }),
    fiber: new THREE.MeshStandardMaterial({ color: 0x220000, emissive: new THREE.Color(1, 0.12, 0.05), emissiveIntensity: 1.5 }),
    tan: poly(0xa89272),
  });
  X = true;
  return m;
}
const R = (G, name) => G.subs.find((s) => s.name === name);
function finish(G, extra) {
  G.build();
  const P = {}; G.subs.forEach((s) => (P[s.name] = s.group));
  return { group: G.group, parts: P, magBase: P.mag ? P.mag.position.clone() : null, ...extra(P) };
}

