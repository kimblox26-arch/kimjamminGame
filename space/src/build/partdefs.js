/** 액체연료 탱크 생성 헬퍼 */
function liquidTank(id, name, tier, diameterKey, height, units, cost) {
  const d = DIAMETER[diameterKey];
  const lf = Math.round(units * 0.45);
  const ox = Math.round(units * 0.55);
  const dry = Math.round(units * RESOURCES.lf.density * 0.125);
  return P({
    id,
    name,
    category: 'tank',
    tier,
    cost,
    mass: dry,
    size: { w: d, h: height },
    art: 'tank',
    artOpts: { stripes: true },
    nodes: [
      { x: 0, y: height / 2, dir: 'top', size: diameterKey },
      { x: 0, y: -height / 2, dir: 'bottom', size: diameterKey },
    ],
    radialAttach: true,
    fuel: { lf, ox },
    drag: { cd: 0.2, area: d * height * 0.5 },
    crashTolerance: 7,
    maxTemp: 1800,
    description: `${d.toFixed(2)} m 급 액체연료/산화제 탱크. 총 ${lf + ox} 단위.`,
  });
}

